/**
 * Generates the reference-data SQL from source files:
 *   1. supabase/migrations/20261019000002_pipe_chart.sql  <- src/lib/pipe/chart-data.ts
 *   2. supabase/seed/inventory_loading_plan.sql           <- the supplier loading-plan .xlsx
 *
 * Usage: npm run seed:generate -- "LOADING PLAN FOR MOTI 2026-10-14.xlsx"
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import ExcelJS from "exceljs";
import { PIPE_CHART } from "../src/lib/pipe/chart-data";
import { SCHEDULES } from "../src/lib/pipe/schedules";
import { parseInventoryWorkbook } from "../src/lib/inventory/excel-import";

const root = path.resolve(__dirname, "..");

const sqlText = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const sqlNum = (v: number | null | undefined) => (v == null || !Number.isFinite(v) ? "null" : String(v));

async function writePipeChart() {
  const columns = ["nps", "nps_value", "dn", "od_mm", ...SCHEDULES.map((s) => s.key)];
  const rows = PIPE_CHART.map(
    ([nps, value, dn, od, walls]) => `  (${[sqlText(nps), sqlNum(value), sqlNum(dn), sqlNum(od), ...walls.map(sqlNum)].join(", ")})`,
  );
  const sql = `-- Pipe dimension chart (ANSI/ASME B36.10 & B36.19). Generated by scripts/generate-seed.ts.
-- Safe to re-run: existing sizes are updated in place.
insert into public.pipe_sizes (${columns.join(", ")})
values
${rows.join(",\n")}
on conflict (nps) do update set
${columns
  .filter((c) => c !== "nps")
  .map((c) => `  ${c} = excluded.${c}`)
  .join(",\n")};
`;
  const file = path.join(root, "supabase/migrations/20261019000002_pipe_chart.sql");
  await writeFile(file, sql, "utf8");
  console.log(`pipe chart: ${PIPE_CHART.length} sizes -> ${path.relative(root, file)}`);
}

async function writeInventory(xlsxPath: string) {
  const workbook = new ExcelJS.Workbook();
  const buffer = await readFile(xlsxPath);
  await workbook.xlsx.load(buffer as unknown as ArrayBuffer);
  const result = parseInventoryWorkbook(workbook);

  for (const issue of result.issues) console.warn(`  row ${issue.row}: ${issue.message}`);

  const columns = ["description", "weight_kg", "unit_price", "stock_qty", "actual_weight", "note"] as const;
  // created_at = now() + n microseconds keeps the rows in Excel order.
  const values = result.rows.map(({ data }, n) =>
    `  (${columns
      .map((c) => {
        const v = data[c];
        return typeof v === "number" ? sqlNum(v) : sqlText(v as string | null);
      })
      .join(", ")}, now() + interval '${n} microseconds')`,
  );

  const sql = `-- Inventory imported from "${path.basename(xlsxPath)}" (sheet "${result.sheetName}").
-- Generated by scripts/generate-seed.ts. Optional: run once to pre-load the inventory.
-- (You can also import the same Excel file from the Inventory page.)
insert into public.inventory_items (${columns.join(", ")}, created_at)
values
${values.join(",\n")};
`;
  await mkdir(path.join(root, "supabase/seed"), { recursive: true });
  const file = path.join(root, "supabase/seed/inventory_loading_plan.sql");
  await writeFile(file, sql, "utf8");
  console.log(`inventory: ${result.rows.length} items (${result.issues.length} issues) -> ${path.relative(root, file)}`);
  return result;
}

async function main() {
  await writePipeChart();
  const xlsx = process.argv[2];
  if (xlsx) {
    const result = await writeInventory(path.resolve(xlsx));
    if (process.argv.includes("--print")) {
      for (const { row, data } of result.rows) {
        console.log(
          [row, data.description, data.weight_kg ?? "", data.unit_price ?? "", data.stock_qty, data.note ?? ""].join(" | "),
        );
      }
    }
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
